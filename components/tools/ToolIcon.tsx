export function getToolIcon(name: ToolIconName): LucideIcon {
  return TOOL_ICONS[name] ?? Wrench;
}

export interface ToolIconProps {
  name: ToolIconName;
  className?: string;
  /** Pixel size for width/height. */
  size?: number;
  strokeWidth?: number;
}

export function ToolIcon({ name, className, size = 20, strokeWidth = 1.75 }: ToolIconProps) {
  const Icon = getToolIcon(name);
  return (
    <Icon
      aria-hidden="true"
      focusable="false"
      className={className}
      width={size}
      height={size}
      strokeWidth={strokeWidth}
    />
  );
}
