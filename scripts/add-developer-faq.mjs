const source = readFileSync(FILE, "utf8");

let working = source;
let inserted = 0;
const missing = [];
const notNeeded = [];

for (const [id, entries] of Object.entries(ADDITIONS)) {
  /* Locate this tool's block by its own id, so anchors cannot collide. */
  const idAt = working.indexOf(`id: "${id}"`);
  if (idAt === -1) {
    missing.push(id);
    continue;
  }

  /* The end of this block is the next tool's id, or the end of the array. */
  const nextAt = working.indexOf('\n  {\n    id: "', idAt);
  const blockEnd = nextAt === -1 ? working.length : nextAt;

  const faqAt = working.indexOf("faq: [", idAt);
  if (faqAt === -1 || faqAt > blockEnd) {
    missing.push(id);
    continue;
  }

  /* The array closes before the block ends; find that closing bracket at the
   * same indent level the entries use. */
  const closeAt = working.indexOf("\n    ],\n    related:", faqAt);
  if (closeAt === -1 || closeAt > blockEnd) {
    missing.push(id);
    continue;
  }

  const current = (working.slice(faqAt, closeAt).match(/question:/g) ?? []).length;
  if (current + entries.length < 3) {
    notNeeded.push(`${id} (${current} + ${entries.length} = ${current + entries.length})`);
    continue;
  }

  const block = entries
    .map(
      (e) =>
        `      {\n        question: ${JSON.stringify(e.question)},\n        answer:\n          ${JSON.stringify(e.answer)},\n      },\n`,
    )
    .join("");

  /* Append after the final existing entry, which already ends with a comma. */
  const insertAt = working.lastIndexOf("      },", closeAt) + "      },\n".length;
  working = working.slice(0, insertAt) + block + working.slice(insertAt);
  inserted += entries.length;
  console.log(`  ${id.padEnd(24)} ${current} -> ${current + entries.length}`);
}

console.log(`\n${inserted} entries across ${Object.keys(ADDITIONS).length} tools`);
if (missing.length) {
  console.log(`\nNOT FOUND (${missing.length}): ${missing.join(", ")}`);
  process.exit(1);
}
if (notNeeded.length) {
  console.log(`\nWOULD STILL BE SHORT: ${notNeeded.join(", ")}`);
  process.exit(1);
}

if (WRITE) {
  writeFileSync(FILE, working);
  console.log("\nwritten");
} else {
  console.log("\ndry run — pass --write to apply");
}
